def resolver_materia(nombre, color_def=''):
    txt_norm = normalizar_texto(nombre)
    for trozo, area, col, ico in AREAS_MAP:
        if trozo in txt_norm:
            return area, color_def or col, ico
    return 'ASIGNATURA', color_def or '#0073bc', 'book'

